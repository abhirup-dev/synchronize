#!/usr/bin/env bun
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = join(root, "src/theme/theme-registry.json");
const outputPath = join(root, "src/theme/registry.generated.ts");
const check = process.argv.includes("--check");

function fail(message) {
  console.error(`theme registry: ${message}`);
  process.exit(1);
}

function readRegistry() {
  const registry = JSON.parse(readFileSync(sourcePath, "utf8"));
  const defaults = registry.defaults?.$value;
  const themes = Object.entries(registry.theme ?? {}).map(([id, entry]) => ({
    id,
    value: entry.$value,
    ...(entry.$extensions?.synchronize ?? {}),
  }));
  const skins = Object.entries(registry.skin ?? {}).map(([id, entry]) => ({
    id,
    value: entry.$value,
    ...(entry.$extensions?.synchronize ?? {}),
  }));

  if (!defaults) fail("missing defaults.$value");
  if (!themes.length) fail("missing theme entries");
  if (!skins.length) fail("missing skin entries");

  for (const theme of themes) {
    if (theme.id !== theme.value) fail(`theme ${theme.id} has mismatched $value ${theme.value}`);
    if (theme.family !== "light" && theme.family !== "dark") fail(`theme ${theme.id} must declare family light|dark`);
    if (!theme.label) fail(`theme ${theme.id} is missing label`);
  }
  for (const skin of skins) {
    if (skin.id !== skin.value) fail(`skin ${skin.id} has mismatched $value ${skin.value}`);
    if (!skin.label) fail(`skin ${skin.id} is missing label`);
  }

  const themeIds = new Set(themes.map((theme) => theme.id));
  const skinIds = new Set(skins.map((skin) => skin.id));
  for (const key of ["initialTheme", "lightTheme", "darkTheme"]) {
    if (!themeIds.has(defaults[key])) fail(`defaults.${key} references unknown theme ${defaults[key]}`);
  }
  if (!skinIds.has(defaults.initialSkin)) fail(`defaults.initialSkin references unknown skin ${defaults.initialSkin}`);
  if (themes.find((theme) => theme.id === defaults.lightTheme)?.family !== "light") fail("defaults.lightTheme must be light family");
  if (themes.find((theme) => theme.id === defaults.darkTheme)?.family !== "dark") fail("defaults.darkTheme must be dark family");

  const normalizes = new Map();
  for (const theme of themes) {
    for (const legacy of theme.normalizes ?? []) {
      if (normalizes.has(legacy)) fail(`legacy theme ${legacy} maps to multiple themes`);
      normalizes.set(legacy, theme.id);
    }
  }

  return {
    defaults,
    themes: themes.sort((a, b) => (a.toolbarOrder ?? 0) - (b.toolbarOrder ?? 0)),
    skins: skins.sort((a, b) => (a.toolbarOrder ?? 0) - (b.toolbarOrder ?? 0)),
    normalizes: [...normalizes.entries()].sort(([a], [b]) => a.localeCompare(b)),
  };
}

function q(value) {
  return JSON.stringify(value);
}

function generate({ defaults, themes, skins, normalizes }) {
  const light = themes.filter((theme) => theme.family === "light").map((theme) => theme.id);
  const dark = themes.filter((theme) => theme.family === "dark").map((theme) => theme.id);
  const themeOptions = themes.map((theme) => ({ value: theme.id, title: theme.label }));
  const skinOptions = skins.map((skin) => ({ value: skin.id, title: skin.label }));
  const legacyEntries = normalizes.map(([legacy, theme]) => `  ${q(legacy)}: ${q(theme)},`).join("\n");

  return `// Generated by web/scripts/generate-theme-registry.mjs. Do not edit by hand.

export const LIGHT_THEMES = ${q(light)} as const;
export const DARK_THEMES = ${q(dark)} as const;
export const ALL_THEMES = ${q(themes.map((theme) => theme.id))} as const;
export const ALL_SKINS = ${q(skins.map((skin) => skin.id))} as const;

export type ThemeName = (typeof ALL_THEMES)[number];
export type SkinName = (typeof ALL_SKINS)[number];

export const DEFAULT_LIGHT_THEME: ThemeName = ${q(defaults.lightTheme)};
export const DEFAULT_DARK_THEME: ThemeName = ${q(defaults.darkTheme)};
export const INITIAL_THEME: ThemeName = ${q(defaults.initialTheme)};
export const INITIAL_SKIN: SkinName = ${q(defaults.initialSkin)};

export const THEME_OPTIONS = ${JSON.stringify(themeOptions, null, 2)} as const;
export const SKIN_OPTIONS = ${JSON.stringify(skinOptions, null, 2)} as const;

const LEGACY_THEME_NORMALIZATION: Record<string, ThemeName> = {
${legacyEntries}
};

export function isThemeName(value: string | null): value is ThemeName {
  return ALL_THEMES.includes(value as ThemeName);
}

export function isSkinName(value: string | null): value is SkinName {
  return ALL_SKINS.includes(value as SkinName);
}

export function normalizeStoredTheme(value: string | null): ThemeName {
  if (value && LEGACY_THEME_NORMALIZATION[value]) return LEGACY_THEME_NORMALIZATION[value];
  return isThemeName(value) ? value : INITIAL_THEME;
}

export function normalizeStoredSkin(value: string | null): SkinName {
  return isSkinName(value) ? value : INITIAL_SKIN;
}
`;
}

const output = generate(readRegistry());
if (check) {
  if (!existsSync(outputPath)) fail("generated registry is missing; run bun run generate:theme-registry");
  const current = readFileSync(outputPath, "utf8");
  if (current !== output) fail("generated registry is stale; run bun run generate:theme-registry");
  console.log("theme registry generated output is current");
} else {
  writeFileSync(outputPath, output, "utf8");
  console.log(`generated ${outputPath.slice(root.length + 1)}`);
}
