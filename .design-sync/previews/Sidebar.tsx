import * as React from 'react';
import * as S from "@ds-stories/web/src/components/Sidebar.stories";

// /design-sync DARK-MODE REFERENCE CARD — owned preview.
// This is the SAME component as its light counterpart; it is rendered with
// data-theme="dark" on the root purely to show the dark palette in the
// gallery. The component is theme-agnostic (light is the default) and
// supports every theme + the glass skin. See .design-sync/conventions.md.
if (typeof document !== "undefined") { document.documentElement.dataset.theme = "dark"; document.documentElement.dataset.skin = "brutal"; }

function compose(S: any, key: string) {
  const meta: any = S.default ?? {};
  const st: any = S[key];
  const args: any = { ...(meta.args ?? {}), ...(st && st.args ? st.args : {}) };
  // Storybook resolves argTypes.mapping (control value -> real arg) before
  // rendering; mirror that so mapped args don't render raw.
  const at: any = { ...(meta.argTypes ?? {}), ...(st && st.argTypes ? st.argTypes : {}) };
  for (const k of Object.keys(args)) {
    const m = at[k] && at[k].mapping;
    if (m && typeof m === 'object' && args[k] in m) args[k] = m[args[k]];
  }
  const title: string = typeof meta.title === 'string' ? meta.title : '';
  const ctx: any = {
    args, name: key, title, kind: title, id: '', componentId: '',
    globals: {}, viewMode: 'story',
    parameters: (st && st.parameters) ?? meta.parameters ?? {},
  };
  let render: (() => any) | null = null;
  if (st && typeof st.render === 'function') render = () => st.render(args, ctx);
  else if (typeof st === 'function') render = () => st(args, ctx);
  else if (typeof meta.render === 'function') render = () => meta.render(args, ctx);
  else {
    const C = (st && st.component) || meta.component;
    if (C) render = () => React.createElement(C, args);
  }
  if (!render) return () => null;
  // [].concat: a single function is legal CSF decorator shorthand. A
  // decorator returning undefined (stubbed addon) falls through to the inner
  // render — otherwise one unrecognized addon blanks the cell silently.
  const decorators: any[] = ([] as any[]).concat((st && st.decorators) ?? []).concat(meta.decorators ?? []);
  return decorators.reduce((inner: any, dec: any) => () => {
    const out = dec(inner, ctx);
    return out === undefined ? inner() : out;
  }, render);
}

export const GroupSelected = /* Group Selected */ compose(S, "GroupSelected");
export const DmSelected = /* Dm Selected */ compose(S, "DmSelected");
export const ActivityDock = /* Activity Dock */ compose(S, "ActivityDock");
export const TypingMode = /* Typing Mode */ compose(S, "TypingMode");
